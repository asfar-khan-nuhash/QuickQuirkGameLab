    // Creates Classroom
    private void createClassroom(){
        String classcode = ClassCodeInput.getText().trim();
        String classname = ClassNameInput.getText().trim();
        
        File filepath = new File("classrooms.csv");
        if ("".equals(ClassNameInput.getText())) {
            missingFieldsPopup();
        } else if ("".equals(ClassCodeInput.getText())){
            missingFieldsPopup();
        } else if (classCodeExists(ClassCodeInput.getText().trim())) {
            CodeExistsPopup();
        } else {
            // Everything is valid and writes to CSV file
            try (FileWriter writer = new FileWriter(filepath, true)) {
                String line = classcode + "," + classname + "," + this.accuname + "\n";
                writer.write(line);
                System.out.println("Data saved successfully!");
                
                // Clear text fields
                ClassNameInput.setText("");
                ClassCodeInput.setText("");
                
                // Creates a learners list csv file and assignment folder
                String learnerlistFilepath = "Educator/" + this.accuname + "/Classrooms/" + classcode + "/Learnerlist.csv";
                String assignmentFilepath = "Educator/" + this.accuname + "/Classrooms/" + classcode + "/Assignments";
                
                File llistpath = new File(learnerlistFilepath);
                File asgnpath = new File(assignmentFilepath);
                
                // Create the folder if it doesn't exist
                llistpath.getParentFile().mkdirs();
                // Creates the learner list
                if (llistpath.createNewFile()){
                    System.out.println("Successfully created Learnerlist.csv");
                } else {
                    System.out.println("Error in making Learnerlist.csv");
                }
                
                // Creates the assignment folder
                asgnpath.mkdirs();

            } catch (IOException e) {
                e.printStackTrace();
                System.out.println("Error writing to CSV file.");
                
            }
        }
    }
    
    public boolean classCodeExists(String code) {
        String classCode = code;

        try (BufferedReader reader = new BufferedReader(new FileReader("classrooms.csv"))) {
            String line;
            while ((line = reader.readLine()) != null) {
                String[] parts = line.split(",");
                if (parts.length > 0 && parts[0].trim().equals(classCode)) {
                    return true;
                }
            }
        } catch (IOException e) {
            e.printStackTrace();
        }

        return false;
    }
    
    private void updateClassroomCombobox(){
        String filePath = "Educator/" + this.accuname + "/Classrooms/";
        File directory = new File(filePath);
        
        if (directory.exists() && directory.isDirectory()) {
            File[] folders = directory.listFiles();

            if (folders != null) {
                for (File folder : folders) {
                    if (folder.isDirectory()) {
                        // Add the folder name (class code) to the dropdown
                        AddLearnerClassroomSelect.addItem(folder.getName()); // For adding learners
                        ViewLearnersClassroomList.addItem(folder.getName()); // For viewing learners
                    }
                }
            }
        }
    }
    
