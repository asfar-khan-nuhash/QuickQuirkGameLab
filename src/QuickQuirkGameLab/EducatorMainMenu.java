    // Helper methods
    
    private boolean learnerFolderExists(String uname){
        File learnerDir = new File("Learner/");
        
        if (learnerDir.exists() && learnerDir.isDirectory()) {
            File[] folders = learnerDir.listFiles();

            if (folders != null) {
                for (File folder : folders) {
                    if (folder.isDirectory() && folder.getName().trim().equals(uname.trim())) {
                        System.out.println("Username: " + folder.getName().trim() + " exists!"); // Debug
                        return true; // Username folder found!
                    }
                }
            }
        }
        System.out.println("Username not found"); // Debug
        return false;
    }
    
