    private void viewLearners(){
        String clinput = (String) ViewLearnersClassroomList.getSelectedItem();
        
        if (ViewLearnersClassroomList.equals("Select a classroom")){
            chooseClassCodePopup();
        } else {
            String selectedClass = (String) ViewLearnersClassroomList.getSelectedItem();
            File classList = new File("Educator/" + this.accuname + "/Classrooms/" + selectedClass + "/Learnerlist.csv");
            
            String[] columnNames = { "Username", "Full Name", "Email", "Math High Score", "English High Score"};
            String[][] rowData = new String[100][5];
            int rowCount = 0;

            try (BufferedReader reader = new BufferedReader(new FileReader(classList))) {
                String line;
                while ((line = reader.readLine()) != null) {
                    String[] parts = line.split(",");
                    if (parts.length == 5) {
                        for (int i = 0; i < 5; i++) {
                            rowData[rowCount][i] = parts[i];
                        }
                        rowCount++;
                    }
                }
            } catch (IOException e) {
                e.printStackTrace();
            }
            
            String[][] trimmedData = new String[rowCount][5];
            for (int i = 0; i < rowCount; i++) {
                for (int j = 0; j < 5; j++) {
                    trimmedData[i][j] = rowData[i][j];
                }
            }
            DefaultTableModel model = new DefaultTableModel(trimmedData, columnNames);
            LearnerList.setModel(model);
        }
    }
    
