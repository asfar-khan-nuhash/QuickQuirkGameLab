    private void SaveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SaveButtonActionPerformed
        File filePath = new File("Learner/" + this.uname + "/accountDetails.csv");
        File tempFilePath = new File ("Learner/" + this.uname + "/temp.csv");

        // New values
        this.fname = EPFnameInput.getText();
        this.email = EPEmailInput.getText();
        this.pass = EPPassInput.getText();
        

        // Updates the account file
        try {
            BufferedReader reader = new BufferedReader(new FileReader(filePath));
            BufferedWriter writer = new BufferedWriter(new FileWriter(tempFilePath));

            String line;
            int lineNumber = 0;

            while ((line = reader.readLine()) != null) {
                switch (lineNumber) {
                    case 0: writer.write(this.fname); break; // Replace fname
                    case 2: writer.write(this.pass); break; // Replace pass
                    case 3: writer.write(this.email); break;// Replace email
                    case 5: writer.write(this.icon); break; // Replaces icon (after choosing it)
                    default: writer.write(line); break;    // Keep original
                }
                writer.newLine();
                lineNumber++;
            }

            reader.close();
            writer.close();

            if (filePath.delete()) {
                if (tempFilePath.renameTo(filePath)) {
                    System.out.println("Updated successfully!"); // Debug
                } else {
                    System.out.println(" Couldn't rename temp file."); // Debug
                }
            } else {
                System.out.println("Couldn't delete original file."); // Debug
            }

        } catch (IOException e) {
            e.printStackTrace();
        }

        // Updates the master file
        String masterFileUpdate = "usermasterlist.csv";
        try {
            File inputFile = new File(masterFileUpdate);
            File tempFile = new File("temp.csv");

            BufferedReader reader = new BufferedReader(new FileReader(inputFile));
            BufferedWriter writer = new BufferedWriter(new FileWriter(tempFile));

            String line;
            while ((line = reader.readLine()) != null) {
                String[] columns = line.split(",");

                if (columns[1].equals(this.uname)) {
                    columns[0] = this.fname;
                    columns[2] = this.pass;
                    columns[3] = this.email;
                }

                writer.write(String.join(",", columns));
                writer.newLine();
            }

            reader.close();
            writer.close();

            // Replace original file with the updated file
            if (inputFile.delete()) {
                tempFile.renameTo(inputFile);
            }

            System.out.println("Master file Update complete");

        } catch (IOException e) {
            e.printStackTrace();
        }

        // Create a new pop up message
        PopupWindow updateSuccess = new PopupWindow();
        updateSuccess.setVisible(true);
        updateSuccess.setMessages("Update Sucessful!","Please log in again to see your changes");
    }//GEN-LAST:event_SaveButtonActionPerformed

