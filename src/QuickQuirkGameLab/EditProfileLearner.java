    public void setTempProfile(String fname, String email, String uname, String pass, String icon){
        this.fname = fname;
        this.email = email;
        this.uname = uname;
        this.pass = pass;
        this.icon = icon;   // This sets the name of the icon
        this.iconPath = "src/img/" + icon + ".png";
        
        System.out.println("\n Display current editing username: " + this.uname);
        
        //Display Profile
        displayTempProfile(this.fname, this.email, this.uname, this.pass, this.icon);
    }
    
    private void displayTempProfile(String fname, String email, String uname, String pass, String icon){
        EPFnameInput.setText(fname);
        EPEmailInput.setText(email);
        EPUnameInput.setText(uname);
        EPPassInput.setText(pass);
        EPProfileIcon.setIcon(new ImageIcon(this.iconPath));
        
        CurrentLoginUsername.setText(uname);
        CurrentLoginName.setText(fname);
        
        this.unlockIcon();
    }
    
    private void unlockIcon(){
        try {
            BufferedReader reader = new BufferedReader(new FileReader("Learner/" + this.uname + "/inventory.csv"));
            String line;

            while ((line = reader.readLine()) != null) {
                // Optional: trim to avoid accidental whitespace
                line = line.trim();

                if (line.equals("ChemistryIcon")) {
                    chemistryUnlocked = true;
                } else if (line.equals("PhysicsIcon")) {
                    physicsUnlocked = true;
                } else if (line.equals("MathsIcon")) {
                    mathsUnlocked = true;
                } else if (line.equals("PlanetIcon")) {
                    planetUnlocked = true;
                }
            }

            reader.close();
        } catch (IOException e) {
            e.printStackTrace();
        }
        
        // Displays the icons in the edit icon menu
        if (chemistryUnlocked == true) {
            ChemistryIconSelect.setIcon(new ImageIcon("src/img/ChemistryIcon.png"));
            ChemistryIconLabel.setText("Chemisty Icon");
        }
        if (physicsUnlocked == true) {
            PhysicsIconSelect.setIcon(new ImageIcon("src/img/PhysicsIcon.png"));
            PhysicsIconLabel.setText("Physics Icon");
        }
        if (mathsUnlocked == true) {
            MathsIconSelect.setIcon(new ImageIcon("src/img/MathsIcon.png"));
            MathsIconLabel.setText("Maths Icon");
        }
        if (planetUnlocked == true) {
            PlanetIconSelect.setIcon(new ImageIcon("src/img/PlanetIcon.png"));
            PlanetIconLabel.setText("Planet Icon");
        }
    }
    
    private void setIcon(String icon){
        String path = "src/img/" + icon + ".png";
        EPProfileIcon.setIcon(new ImageIcon(path));
        this.icon = icon;
        this.iconPath = path;
    }
    
